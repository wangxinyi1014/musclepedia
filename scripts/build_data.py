#!/usr/bin/env python3
"""
build_data.py — 从 data/exercises.json 生成增强数据文件。

产物：
  data/exercises.csv           平铺表格（含英文与中文说明）
  data/exercises.sqlite.sql    SQLite 建表 + INSERT
  data/exercises.postgres.sql  PostgreSQL 建表 + INSERT
  data/stats.json              数据统计与完整性校验结果
  docs/data-report.md          数据质量报告（自动生成）

用法：python3 scripts/build_data.py
"""
import csv
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
SRC = DATA / "exercises.json"

LANGS = ["en", "es", "it", "tr", "ru", "zh", "hi", "pl", "ko", "fr"]


def load():
    with open(SRC, encoding="utf-8") as f:
        return json.load(f)


def esc_sql(s: str) -> str:
    return (s or "").replace("'", "''")


def flatten(ex):
    return {
        "id": ex["id"],
        "name": ex["name"],
        "category": ex["category"],
        "body_part": ex["body_part"],
        "equipment": ex["equipment"],
        "target": ex["target"],
        "muscle_group": ex.get("muscle_group", ""),
        "secondary_muscles": "; ".join(ex.get("secondary_muscles") or []),
        "instructions_en": ex["instructions"].get("en", ""),
        "instructions_zh": ex["instructions"].get("zh", ""),
        "image": ex.get("image", ""),
        "gif_url": ex.get("gif_url", ""),
        "attribution": ex.get("attribution", ""),
    }


def write_csv(exercises):
    rows = [flatten(e) for e in exercises]
    cols = list(rows[0].keys())
    path = DATA / "exercises.csv"
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    print(f"[ok] {path.name}  {len(rows)} 行")


def write_sql(exercises, flavor: str):
    if flavor == "sqlite":
        path = DATA / "exercises.sqlite.sql"
        id_type = "TEXT"
    else:
        path = DATA / "exercises.postgres.sql"
        id_type = "VARCHAR(16)"
    lines = []
    lines.append("-- Fit Atlas exercises dataset — generated by scripts/build_data.py")
    lines.append(f"-- source: data/exercises.json ({len(exercises)} rows)")
    lines.append("")
    if flavor == "postgres":
        lines.append("CREATE TABLE IF NOT EXISTS exercises (")
        lines.append("  id VARCHAR(16) PRIMARY KEY,")
    else:
        lines.append("CREATE TABLE IF NOT EXISTS exercises (")
        lines.append("  id TEXT PRIMARY KEY,")
    lines.append("  name TEXT NOT NULL,")
    lines.append("  category TEXT,")
    lines.append("  body_part TEXT,")
    lines.append("  equipment TEXT,")
    lines.append("  target TEXT,")
    lines.append("  muscle_group TEXT,")
    lines.append("  secondary_muscles TEXT,")
    lines.append("  instructions TEXT,      -- JSON object, 10 languages")
    lines.append("  instruction_steps TEXT, -- JSON object, 10 languages")
    lines.append("  image TEXT,")
    lines.append("  gif_url TEXT,")
    lines.append("  attribution TEXT")
    lines.append(");")
    lines.append("")
    for e in exercises:
        ins = json.dumps(e["instructions"], ensure_ascii=False)
        steps = json.dumps(e.get("instruction_steps", {}), ensure_ascii=False)
        sec = "; ".join(e.get("secondary_muscles") or [])
        lines.append(
            "INSERT INTO exercises (id, name, category, body_part, equipment, target, "
            "muscle_group, secondary_muscles, instructions, instruction_steps, image, gif_url, attribution) VALUES ("
            f"'{esc_sql(e['id'])}', '{esc_sql(e['name'])}', '{esc_sql(e['category'])}', "
            f"'{esc_sql(e['body_part'])}', '{esc_sql(e['equipment'])}', '{esc_sql(e['target'])}', "
            f"'{esc_sql(e.get('muscle_group',''))}', '{esc_sql(sec)}', "
            f"'{esc_sql(ins)}', '{esc_sql(steps)}', "
            f"'{esc_sql(e.get('image',''))}', '{esc_sql(e.get('gif_url',''))}', '{esc_sql(e.get('attribution',''))}'"
            ");"
        )
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"[ok] {path.name}  {len(exercises)} 条 INSERT")


def write_stats(exercises):
    by = defaultdict(Counter)
    for e in exercises:
        by["category"][e["category"]] += 1
        by["body_part"][e["body_part"]] += 1
        by["equipment"][e["equipment"]] += 1
        by["target"][e["target"]] += 1
        by["muscle_group"][e.get("muscle_group", "")] += 1

    def top(c, n=None):
        return [{"key": k, "count": v} for k, v in c.most_common(n)]

    langs = Counter()
    missing_langs = 0
    for e in exercises:
        for l in LANGS:
            if l in e["instructions"]:
                langs[l] += 1
            else:
                missing_langs += 1

    # 媒体完整性
    missing_media = []
    for e in exercises:
        for f in (e.get("image"), e.get("gif_url")):
            if f and not (ROOT / f).exists():
                missing_media.append({"id": e["id"], "file": f})

    stats = {
        "total": len(exercises),
        "unique_ids": len({e["id"] for e in exercises}),
        "languages": dict(langs),
        "missing_language_slots": missing_langs,
        "missing_media": missing_media[:20],
        "missing_media_count": len(missing_media),
        "by_category": top(by["category"]),
        "by_body_part": top(by["body_part"]),
        "by_equipment": top(by["equipment"]),
        "by_target": top(by["target"]),
        "by_muscle_group": top(by["muscle_group"], 15),
    }
    with open(DATA / "stats.json", "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)
    print(f"[ok] stats.json  总量 {stats['total']}，缺失媒体 {stats['missing_media_count']}")


def write_report(exercises, stats):
    lines = []
    lines.append("# 数据质量报告（自动生成）")
    lines.append("")
    lines.append(f"> 由 `scripts/build_data.py` 于运行当日生成，源数据 `data/exercises.json`。")
    lines.append("")
    lines.append("## 概览")
    lines.append("")
    lines.append(f"- 动作总数：**{stats['total']}**")
    lines.append(f"- 唯一 ID：**{stats['unique_ids']}**（重复 ID 数：{stats['total'] - stats['unique_ids']}）")
    lines.append(f"- 缺失语言槽位：**{stats['missing_language_slots']}**（应为 0）")
    lines.append(f"- 缺失媒体文件：**{stats['missing_media_count']}**（应为 0）")
    lines.append("")
    lines.append("## 语言覆盖")
    lines.append("")
    lines.append("| 语言 | 覆盖词条数 |")
    lines.append("| --- | --- |")
